import gradio as gr
import pandas as pd
import plotly.express as px

def update_dashboard(advertising_channel):
    # 1. Scatter plot: Chosen advertising channel vs Sales colored by City
    fig_scatter = px.scatter(
        df,
        x=advertising_channel,
        y="sales",
        color="City",
        hover_data=["City"],
        title=f"{advertising_channel} Advertising vs Sales by City",
        template="plotly_white"
    )

    # 2. Bar plot: Total or average sales per City
    df_city_sales = df.groupby("City")["sales"].mean().reset_index().sort_values(by="sales", ascending=False)
    fig_bar = px.bar(
        df_city_sales,
        x="City",
        y="sales",
        color="City",
        title="Average Sales by City",
        template="plotly_white"
    )

    return fig_scatter, fig_bar

# Define the Gradio Interface using Blocks
with gr.Blocks() as demo:
    gr.Markdown("# 📊 City Sales & Advertising Dashboard")
    gr.Markdown("Explore how sales change across different cities based on advertising spend.")

    with gr.Row():
        channel_dropdown = gr.Dropdown(
            choices=["TV", "radio", "newspaper"],
            value="TV",
            label="Select Advertising Channel for Scatter Plot"
        )

    with gr.Row():
        scatter_plot = gr.Plot(label="Ad Spend vs Sales Scatter Plot")
        bar_plot = gr.Plot(label="Average Sales by City Bar Plot")

    # Interactivity
    channel_dropdown.change(
        fn=update_dashboard,
        inputs=channel_dropdown,
        outputs=[scatter_plot, bar_plot]
    )

    # Load the initial dashboard views
    demo.load(
        fn=update_dashboard,
        inputs=channel_dropdown,
        outputs=[scatter_plot, bar_plot]
    )

# Launch the dashboard with inline display capability for Google Colab
demo.launch(inline=True, share=True)

